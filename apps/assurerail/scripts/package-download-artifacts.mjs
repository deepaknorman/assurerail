#!/usr/bin/env node

import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = path.resolve(appRoot, "../..");
const manifestPath = path.join(repoRoot, "docs/operations/phase1-da/artifact-manifest.json");
const outputPath = path.join(appRoot, "src/generated/download-artifacts.ts");
const checkOnly = process.argv.includes("--check");
const servedClassifications = new Set(["PUBLIC", "SHARED_PASSWORD"]);
const allowedClassifications = new Set(["PUBLIC", "SHARED_PASSWORD", "AUTHENTICATED", "INTERNAL"]);

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const current = manifest.artifacts.filter((item) => item.status === "CURRENT");
const ids = new Set();
const routes = new Set();
for (const item of current) {
  if (typeof item.id !== "string" || !/^[A-Z0-9-]+$/.test(item.id)) throw new Error("CURRENT artifact has an invalid id");
  if (ids.has(item.id)) throw new Error(`${item.id} duplicates an artifact id`);
  ids.add(item.id);
  if (!allowedClassifications.has(item.classification)) throw new Error(`${item.id} has an invalid classification`);
}
for (const item of current.filter((entry) => entry.plannedDownloadRoute)) {
  if (!/^\/downloads\/[a-z0-9/_-]+$/.test(item.plannedDownloadRoute) || item.plannedDownloadRoute.includes("//") || item.plannedDownloadRoute === "/downloads/access") {
    throw new Error(`${item.id} has an unsafe plannedDownloadRoute`);
  }
  if (routes.has(item.plannedDownloadRoute)) throw new Error(`${item.id} duplicates a plannedDownloadRoute`);
  routes.add(item.plannedDownloadRoute);
}
const catalog = current.map((item) => ({
  id: item.id,
  title: item.title,
  classification: item.classification,
  status: item.status,
  route: item.plannedDownloadRoute ?? null,
  releaseGate: item.releaseGate ?? null,
}));

const packaged = [];
for (const item of current.filter((entry) => servedClassifications.has(entry.classification))) {
  if (!item.output || !item.plannedDownloadRoute) throw new Error(`${item.id} requires output and plannedDownloadRoute`);
  const sourcePath = path.resolve(repoRoot, item.output);
  if (!sourcePath.startsWith(repoRoot + path.sep)) throw new Error(`${item.id} output escapes repository`);
  packaged.push({
    id: item.id,
    title: item.title,
    classification: item.classification,
    route: item.plannedDownloadRoute,
    html: await readFile(sourcePath, "utf8"),
  });
}

const authenticatedOrInternal = current.filter((item) => !servedClassifications.has(item.classification));
if (authenticatedOrInternal.some((item) => packaged.some((artifact) => artifact.id === item.id))) {
  throw new Error("Protected workspace/internal artifact selected for web packaging");
}

const output = `/* Generated by scripts/package-download-artifacts.mjs. Do not edit. */
import "server-only";

export type DownloadClassification = "PUBLIC" | "SHARED_PASSWORD" | "AUTHENTICATED" | "INTERNAL";
export type DownloadCatalogItem = {
  id: string;
  title: string;
  classification: DownloadClassification;
  status: "CURRENT";
  route: string | null;
  releaseGate: string | null;
};
export type PackagedDownloadArtifact = {
  id: string;
  title: string;
  classification: "PUBLIC" | "SHARED_PASSWORD";
  route: string;
  html: string;
};

export const DOWNLOAD_CATALOG = ${JSON.stringify(catalog, null, 2)} as const satisfies readonly DownloadCatalogItem[];

const PACKAGED_DOWNLOAD_ARTIFACTS = ${JSON.stringify(packaged, null, 2)} as const satisfies readonly PackagedDownloadArtifact[];

export function findDownloadCatalogItem(id: string) {
  return DOWNLOAD_CATALOG.find((item) => item.id === id);
}

export function findPackagedDownloadArtifact(id: string) {
  return PACKAGED_DOWNLOAD_ARTIFACTS.find((item) => item.id === id);
}
`;

if (checkOnly) {
  let currentOutput = "";
  try { currentOutput = await readFile(outputPath, "utf8"); } catch { /* reported below */ }
  if (currentOutput !== output) {
    console.error("download artifact package is outdated");
    process.exit(1);
  }
  console.log(`PASS download package current: ${packaged.length} served, ${authenticatedOrInternal.length} metadata-only`);
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, output, "utf8");
  console.log(`packaged ${packaged.length} downloadable artifacts; kept ${authenticatedOrInternal.length} metadata-only`);
}
